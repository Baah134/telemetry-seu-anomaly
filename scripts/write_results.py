"""Generate RESULTS.md from the results files (no hand-typed numbers).
Usage: python -m scripts.write_results
"""
import json
from pathlib import Path

R = Path("results")


def j(p):
    return json.loads((R / p).read_text(encoding="utf-8"))


def md(p):
    t = (R / "tables" / p).read_text(encoding="utf-8").strip()
    return t


def cmp(na, a, sa, nb, b, sb):
    """Sentence fragment comparing two mean +- sd results (3 seeds)."""
    d = a - b
    if abs(d) <= max(sa, sb, 1e-9) * 2:
        return f"{na} - {nb} = {d:+.3f}, within two seed standard deviations (not resolved with 3 seeds)"
    return f"{na} - {nb} = {d:+.3f} ({na} {'higher' if d > 0 else 'lower'}, beyond two seed standard deviations)"


def main():
    D = j("detection_summary.json")
    F = j("faults_summary.json")
    S = j("data_summary.json")
    C = j("c_host_check.json")
    res = {r["model"] + "|" + r["spacecraft"]: r for r in j("resources.json")}
    g = lambda m, t="telemanom", s="ALL", k="event_f1": D[f"{m}|{t}|{s}"][k]
    i8, f32, lstm, per = (g("tiny_int8"), g("tiny_f32"), g("lstm"), g("persist"))
    rnd_pa = g("random", "percentile", "ALL", "pa_f1")
    fa = lambda m, t="telemanom": g(m, t, "ALL", "fa_per_1k")["mean"]
    kb_i8 = res["Tiny MLP INT8 (per channel)|SMAP"]["weight bytes"], res["Tiny MLP INT8 (per channel)|MSL"]["weight bytes"]
    kb_l = res["LSTM 2x80 float32 (per channel)|SMAP"]["weight bytes"], res["LSTM 2x80 float32 (per channel)|MSL"]["weight bytes"]
    cl = F["clean"]
    sw = F["sweep"]
    dm = F["damage"]
    tr = F["transient"]
    pr = F.get("protect", {})
    nf = F.get("no_fault_f1", {})

    L = []
    a = L.append
    a("# Results (simulation only)\n")
    a("Generated by `scripts/write_results.py` from `results/*.json`. Every number is traceable to a "
      "results file; tables are copied from `results/tables/`. Nothing here is a hardware or radiation result.\n")
    a(f"Data: {S['ALL']['channels']} channels ({S['SMAP']['channels']} SMAP, {S['MSL']['channels']} MSL), "
      f"{S['ALL']['anomaly_sequences']} labeled anomaly sequences, {S['ALL']['anomaly_point_frac'] * 100:.1f}% of "
      "test points labeled anomalous (docs/DATA.md). Models trained with 3 seeds; thresholds use only the "
      "validation split (end of each training series) or, for the telemanom pipeline, test errors without labels.\n")

    a("## 1. Detection\n")
    a("### 1.1 Headline: telemanom's own detection pipeline (event-wise, SMAP + MSL)\n")
    a(f"- Tiny MLP INT8: event F1 **{i8['mean']:.3f} ± {i8['std']:.3f}**; float32 {f32['mean']:.3f} ± {f32['std']:.3f}; "
      f"LSTM 2x80 {lstm['mean']:.3f} ± {lstm['std']:.3f}; persistence {per['mean']:.3f}.")
    a(f"- {cmp('INT8', i8['mean'], i8['std'], 'LSTM', lstm['mean'], lstm['std'])}. INT8 uses "
      f"{kb_i8[0]:,}–{kb_i8[1]:,} weight bytes per channel vs {kb_l[0]:,}–{kb_l[1]:,} for the LSTM "
      f"({min(kb_l[0] / kb_i8[0], kb_l[1] / kb_i8[1]):.0f}–{max(kb_l[0] / kb_i8[0], kb_l[1] / kb_i8[1]):.0f}x less).")
    m_i8, m_l = g("tiny_int8", s="MSL"), g("lstm", s="MSL")
    a(f"- MSL alone: INT8 {m_i8['mean']:.3f} ± {m_i8['std']:.3f} vs LSTM {m_l['mean']:.3f} ± {m_l['std']:.3f}; "
      f"{cmp('INT8', m_i8['mean'], m_i8['std'], 'LSTM', m_l['mean'], m_l['std'])}.")
    a(f"- Quantization: {cmp('INT8', i8['mean'], i8['std'], 'float32', f32['mean'], f32['std'])}.")
    a(f"- False-alarm events per 1,000 steps: INT8 {fa('tiny_int8'):.2f}, LSTM {fa('lstm'):.2f}, persistence "
      f"{fa('persist'):.2f}.\n")
    a(md("detection_telemanom.md") + "\n")

    a("### 1.2 The thresholding protocol changes the conclusion\n")
    pi8, pper = g("tiny_int8", "percentile"), g("persist", "percentile")
    a(f"With a fixed threshold (99.5th percentile of validation errors), every method raises ~"
      f"{fa('tiny_int8', 'percentile'):.1f} false-alarm events per 1,000 steps, event precision collapses to "
      f"{g('tiny_int8', 'percentile', 'ALL', 'event_precision')['mean']:.2f}, and **persistence beats the tiny "
      f"model** (event F1 {pper['mean']:.3f} vs {pi8['mean']:.3f}). Under telemanom's windowed, pruned threshold "
      f"the order flips ({per['mean']:.3f} vs {i8['mean']:.3f}). Same models, same data: the detection protocol "
      "decides the ranking.\n")
    a(md("detection_percentile.md") + "\n")
    a("<details><summary>NDT fitted on validation errors</summary>\n\n" + md("detection_ndt.md") + "\n\n</details>\n")

    a("### 1.3 Point adjustment and benchmark sanity\n")
    a(f"- Random scores reach a point-adjusted F1 of **{rnd_pa['mean']:.3f}** (fixed threshold), higher than every "
      f"real method's PA-F1 and against an unadjusted point F1 of "
      f"{g('random', 'percentile', 'ALL', 'point_f1')['mean']:.3f}. PA-F1 is therefore never used as evidence here.")
    a("- Trivial methods already catch most labeled anomalies somewhere (event recall below; false alarms are not "
      "reflected in recall):\n")
    a(md("benchmark_sanity.md") + "\n")

    a("## 2. Resources\n")
    a(md("resources.md") + "\n")
    a(f"Host check of the ESP32 C code: bit-exact with the NumPy integer reference on "
      f"{C['bit_exact']}/{C['windows']} windows (channel {C['chan']}, host gcc; not an ESP32 measurement).\n")

    a("## 3. Simulated SEU fault injection\n")
    a(f"Subset: {', '.join(F['subset'])} (5 SMAP + 5 MSL, drawn by seed before any fault result), training seed 0, "
      f"telemanom detection. Only {F['n_events_subset']} labeled events, so event F1 moves in steps of about "
      f"{1 / F['n_events_subset']:.2f}. Clean event F1 on the subset: INT8 {cl['int8']['event_f1']:.3f}, "
      f"float32 {cl['f32']['event_f1']:.3f}. 100 Monte Carlo trials per condition.\n")
    a("### 3.1 Persistent weight flips: INT8 is bounded, float32 is not\n")
    a(f"- float32, 100 flips: {sw['f32|100']['nonfinite_trial_frac'] * 100:.0f}% of trials produce NaN/inf forecasts; "
      f"event F1 {sw['f32|100']['event_f1_mean']:.3f} (clean {cl['f32']['event_f1']:.3f}). A NaN poisons the running "
      "error average, so the detector goes silent from that point.")
    a(f"- INT8, 100 flips: no non-finite values are possible; {sw['int8|100']['catastrophic_frac'] * 100:.0f}% "
      f"catastrophic trials; event F1 {sw['int8|100']['event_f1_mean']:.3f}.")
    a(f"- **Detection F1 does not track model health.** With the same 100 flips, "
      f"{dm['int8|100']['frac_mse_gt_2x'] * 100:.0f}% of INT8 models have more than 2x their clean forecast error on "
      f"normal data ({dm['int8|100']['frac_mse_gt_10x'] * 100:.0f}% more than 10x), yet event F1 is "
      f"{'higher' if sw['int8|100']['event_f1_mean'] > cl['int8']['event_f1'] else 'not lower'} than clean. A damaged "
      "forecaster still flags large deviations, which many SMAP/MSL anomalies are. Onboard, model health has to be "
      "checked directly (e.g. checksums), not inferred from the detector's output.\n")
    a(md("fault_sweep.md") + "\n")
    a(md("fault_damage.md") + "\n")
    a("### 3.2 Transient accumulator / activation upsets\n")
    a(f"At one upset per 100 inferences, {tr['f32|0.01']['catastrophic_frac'] * 100:.0f}% of float32 trials are "
      f"catastrophic vs {tr['int8|0.01']['catastrophic_frac'] * 100:.0f}% for INT8; at one per 10, "
      f"{tr['f32|0.1']['catastrophic_frac'] * 100:.0f}% vs {tr['int8|0.1']['catastrophic_frac'] * 100:.0f}%.\n")
    a(md("fault_transient.md") + "\n")
    a("### 3.3 Bit position and layer\n")
    a("See `figures/fault_bitpos.png` and `results/faults_summary.json` (`bitpos`). float32 exponent bits (esp. bit 30) "
      "and sign bits dominate; for INT8 only the output layer's high bits change forecasts often. Per flipped bit the "
      "output layer is the most sensitive, but the input layer holds most of the bits.\n")
    if pr:
        a("### 3.4 Protections\n")
        a("Each protection is compared with its own fault-free F1, because clamp and the sanity check act on every "
          "inference.\n")
        for kind, lab in (("int8", "INT8"), ("f32", "float32")):
            best = max((p for p in ("clamp", "sanity", "tmr_L2", "tmr_L0", "scrub", "combined")
                        if f"{kind}|100|{p}" in pr), key=lambda p: pr[f"{kind}|100|{p}"]["event_f1_mean"])
            a(f"- {lab}, 100 flips: unprotected F1 {pr[f'{kind}|100|none']['event_f1_mean']:.3f}; highest with "
              f"`{best}` {pr[f'{kind}|100|{best}']['event_f1_mean']:.3f} (its fault-free F1 "
              f"{nf.get(f'{kind}|{best}', cl[kind]['event_f1']):.3f}).")
        sd_i8 = pr["int8|100|none"]["event_f1_std"]
        a(f"- INT8: every protection's mean F1 lies within one trial standard deviation ({sd_i8:.3f}) of the "
          "unprotected value or below it; faults did not break INT8 detection, so there was little to recover. "
          "The sanity check lowers F1 even without faults (it also hides real out-of-range anomalies).")
        a("- float32: the activation clamp gives the highest F1 but also raises fault-free F1 (bounded outputs "
          "help on this benchmark); CRC scrubbing recovers to about the clean level only with verify-then-commit "
          "release of outputs (a naive version was worse than no protection, docs/DECISIONS.md #28).")
        a("")
        a(md("fault_protect.md") + "\n")
        si = F.get("scrub_interval")
        if si:
            a("Checksum interval (INT8, 10 flips): " + "; ".join(
                f"K={K}: F1 {v['event_f1_mean']:.3f}, {v['mean_corrupt_inferences']:.0f} corrupted inferences, "
                f"{v['bytes_checked_per_inference']:.0f} B checked/inference" for K, v in si.items()) + ".\n")

    a("## 4. What this does NOT show\n")
    a("- Radiation behaviour: faults are simulated bit flips in software, uniform over stored bits.")
    a("- ESP32 performance: latency/energy are estimates; the C code was only checked on a host compiler.")
    a("- Generality: one benchmark with known flaws; the fault subset has 13 labeled events.")
    a("- Telemanom parity: the port follows telemanom/errors.py but was not run side by side with the original "
      "(docs/DECISIONS.md #19).")
    (Path("RESULTS.md")).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("RESULTS.md written,", len(L), "blocks")


if __name__ == "__main__":
    main()
