"""Export one channel's INT8 tiny model as a C header for the ESP32 sketch, with stored
input windows and the NumPy integer reference's expected outputs (bit-exact check).

Usage: python -m scripts.export_c [--chan <id>] [--n-windows 8] [--out <header path>]
Default: first channel of the fault subset, 8 windows spread over the validation and test
windows, written to export/esp32_infer/model_data.h and export/expected_outputs.json.
`scripts/check_c_host.py` compiles the same C code on the host for 1,000 windows.
"""
import argparse
import json
from pathlib import Path

import numpy as np

N_TEST_WINDOWS = 8
DEFAULT_OUT = "export/esp32_infer/model_data.h"


def carr(name, a, ctype):
    flat = ", ".join(str(int(v)) for v in np.asarray(a).reshape(-1))
    return f"static const {ctype} {name}[{np.asarray(a).size}] = {{{flat}}};\n"


def build(chan=None, n_windows=N_TEST_WINDOWS):
    import torch
    from scripts.run_faults import pick_subset
    from src.data.loader import W, load_channel, load_labels, windows
    from src.models.nets import TinyMLP
    from src.quant.int8 import float_layers, quantize
    chan = chan or pick_subset()[0]
    row = next(r for r in load_labels().to_dict("records") if r["chan_id"] == chan)
    ch = load_channel(row)
    n_fit = len(ch.train) - int(round(0.2 * len(ch.train)))
    Xall, _ = windows(ch.train, ch)
    tgt = np.arange(W, len(ch.train))
    Xf, Xv = Xall[tgt < n_fit], Xall[tgt >= n_fit]
    ck = torch.load(Path("results/models") / f"{chan}_s0.pt")
    m = TinyMLP(ck["in_dim"])
    m.load_state_dict(ck["tiny"])
    qm = quantize(float_layers(m), Xf)
    Xt, _ = windows(ch.test, ch)
    pool = np.concatenate([Xv, Xt])          # validation windows, then test windows
    idx = np.linspace(0, len(pool) - 1, n_windows).astype(int)
    xq = qm.quantize_input(pool[idx])
    yq = qm.forward_int(xq)
    h = [f"// Auto-generated by scripts/export_c.py. Channel {chan}, training seed 0.\n",
         "// INT8 tiny MLP: symmetric per-channel weights, per-tensor activations, int32 bias,\n",
         "// fixed-point requantization (Q31 multiplier M0 + right shift).\n#pragma once\n#include <stdint.h>\n",
         f"#define IN_DIM {qm.W[0].shape[1]}\n#define H1 {qm.W[0].shape[0]}\n#define H2 {qm.W[1].shape[0]}\n",
         f"#define N_TEST {n_windows}\n",
         f"static const float INPUT_SCALE = {qm.s_in:.9e}f;\nstatic const float OUTPUT_SCALE = {qm.s_out:.9e}f;\n"]
    for l in range(3):
        h.append(carr(f"L{l + 1}_W", qm.W[l], "int8_t"))
        h.append(carr(f"L{l + 1}_B", qm.b[l], "int32_t"))
        h.append(carr(f"L{l + 1}_M", qm.M0[l], "int32_t"))
        h.append(carr(f"L{l + 1}_S", qm.sh[l], "int8_t"))
    h.append(carr("TEST_X", xq, "int8_t"))
    h.append(carr("TEST_Y_EXPECTED", yq, "int8_t"))
    return chan, qm, idx, yq, "".join(h)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chan")
    ap.add_argument("--n-windows", type=int, default=N_TEST_WINDOWS)
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args()
    chan, qm, idx, yq, header = build(a.chan, a.n_windows)
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header, encoding="utf-8")
    if a.out == DEFAULT_OUT:
        Path("export/expected_outputs.json").write_text(json.dumps(
            {"chan": chan, "weight_bytes": qm.n_weight_bytes, "pool": "validation windows, then test windows",
             "window_indices": idx.tolist(), "expected_int8": yq.astype(int).tolist(),
             "expected_real": (yq.astype(float) * qm.s_out).tolist()}, indent=2), encoding="utf-8")
    print(f"exported {chan}: {qm.n_weight_bytes} weight bytes; {a.n_windows} windows, "
          f"{len(set(yq.tolist()))} distinct outputs -> {out}")


if __name__ == "__main__":
    main()
